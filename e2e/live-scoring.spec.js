import { test, expect } from '@playwright/test';

test('live score corrections, official replacement, day stats and all categories stay readable', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install({ time: new Date('2026-11-19T02:30:00Z') });
  await page.goto('/e2e/fixtures/live-scoring.html');
  const score = page.locator('.hl-matchup-score__team > b').first();
  const status = page.locator('.hl-live-scoring-status');
  await expect(score).toHaveText('1.00');
  await expect(status).toContainText('Provisional scores');
  await expect(page.locator('.hl-matchup-player--home').first().locator('.hl-matchup-stat:not([title="Games played in this matchup"])')).toHaveCount(13);
  await page.getByRole('button', { name: 'Simulate corrected', exact: true }).click();
  await page.clock.fastForward(119_000);
  await expect(score).toHaveText('1.00');
  await page.clock.fastForward(1_001);
  await expect(score).toHaveText('0.60');
  await page.getByRole('switch', { name: 'Daily statistics' }).click();
  await expect(score).toHaveText('0.60');
  await expect(status).toContainText('Provisional scores');
  await page.getByRole('switch', { name: 'Daily statistics' }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('provisional-scores.png'), fullPage: false });
  await page.getByRole('button', { name: 'Simulate official', exact: true }).click();
  await page.clock.fastForward(120_001);
  await expect(score).toHaveText('0.80');
  await expect(status).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('official-replacement.png'), fullPage: false });
  await page.getByRole('button', { name: 'Simulate delayed', exact: true }).click();
  await page.getByRole('button', { name: 'Read latest scores', exact: true }).click();
  await expect(status).toContainText('Live updates delayed');
  await page.getByRole('button', { name: 'Simulate final', exact: true }).click();
  await page.getByRole('button', { name: 'Read latest scores', exact: true }).click();
  await expect(score).toHaveText('0.80');
  await expect(status).toHaveCount(0);
  const requests = await page.getByLabel('Score requests').textContent();
  await page.clock.fastForward(360_001);
  await expect(page.getByLabel('Score requests')).toHaveText(requests);
  expect(errors).toEqual([]);
});
